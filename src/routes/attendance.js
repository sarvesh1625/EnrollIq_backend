const router = require('express').Router()
const { protect } = require('../middleware/auth')
const c = require('../controllers/attendanceController')
router.use(protect)
router.get  ('/summary',     c.getSummary)
router.get  ('/history',     c.getHistory)
router.get  ('/roster',      c.roster)
router.get  ('/report',      c.report)
// (CSV export of attendance is now a Super Admin tool — see routes/superadminData.js)
router.get  ('/leaves',      c.listLeaves)
router.patch('/leaves/:id',  c.decideLeave)
router.get  ('/',            c.getAttendance)
router.post ('/mark-bulk',   c.markBulk)
router.get  ('/student/:id', c.getStudentAttendance)
module.exports = router